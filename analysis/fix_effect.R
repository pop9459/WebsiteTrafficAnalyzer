# Effect of the KAP-68 fix (Apache serves only public/) on outgoing traffic.
#
# Usage (from the repo root, after scripts/fetch_logs.sh):
#   Rscript analysis/fix_effect.R [before_log.gz] [after_log ...]
# Defaults: the container log of the 7 Oct 2026 VPS backup (9 Jul - 7 Oct
# 09:50 UTC) as "before", data/raw/vps/access.log* as "after".
#
# Writes analysis/fix_effect_summary.md and analysis/figures/06_fix_effect.png.
# Both contain aggregates only.

suppressPackageStartupMessages({
  library(dplyr)
  library(ggplot2)
})
devtools::load_all(quiet = TRUE)

invisible(Sys.setlocale("LC_TIME", "C"))

args <- commandArgs(trailingOnly = TRUE)
before_file <- if (length(args)) args[[1]] else "../data/vps_backup_20261007/container_331fe250f051-json.log.gz"
after_files <- if (length(args) > 1) args[-1] else sort(list.files("data/raw/vps", pattern = "^access\\.log", full.names = TRUE))
stopifnot(file.exists(before_file), length(after_files) > 0)

salt <- get_salt()
load_requests <- function(files) {
  raw <- dplyr::bind_rows(lapply(files, read_raw_log))
  access <- raw[raw$stream %in% "stdout", ]
  parsed <- parse_access_log(access$line)
  parsed[parsed$parse_ok, ] |>
    anonymise_requests(salt) |>
    classify_requests()
}

before <- load_requests(before_file)
after <- load_requests(after_files)

# The fix went live with the restart that created the new log files.
fix_time <- min(after$time)
before <- filter(before, time < fix_time)
requests <- bind_rows(
  mutate(before, period = "before"),
  mutate(after, period = "after")
) |>
  mutate(
    period = factor(period, levels = c("before", "after")),
    day = as.Date(time),
    # Probe families whose 2xx answer means that a file was really served.
    exposure_probe = probe_family %in% c("vcs", "env", "config_leak", "backup"),
    exposed = exposure_probe & status >= 200 & status < 300,
    git_objects = grepl("^/\\.git/objects/", path)
  )

period_summary <- requests |>
  group_by(period) |>
  summarise(
    from = min(time), to = max(time),
    days = as.numeric(difftime(max(time), min(time), units = "days")),
    requests = n(),
    gb_out = sum(bytes, na.rm = TRUE) / 1e9,
    exposure_probes = sum(exposure_probe),
    exposed_2xx = sum(exposed),
    git_objects_2xx = sum(git_objects & status >= 200 & status < 300),
    git_objects_gb = sum(bytes[git_objects & status >= 200 & status < 300], na.rm = TRUE) / 1e9,
    exposed_gb = sum(bytes[exposed], na.rm = TRUE) / 1e9,
    .groups = "drop"
  ) |>
  mutate(
    requests_per_day = requests / days,
    mb_out_per_day = gb_out * 1000 / days,
    exposed_per_day = exposed_2xx / days
  )

status_of_probes <- requests |>
  filter(exposure_probe) |>
  mutate(status_class = paste0(status %/% 100, "xx")) |>
  count(period, status_class) |>
  group_by(period) |>
  mutate(share = n / sum(n)) |>
  ungroup()

b <- period_summary[period_summary$period == "before", ]
a <- period_summary[period_summary$period == "after", ]
drop_bytes <- 1 - a$mb_out_per_day / b$mb_out_per_day
drop_exposed <- 1 - a$exposed_per_day / b$exposed_per_day

fmt_time <- function(x) format(x, "%d %b %H:%M UTC")
md_table <- function(df) {
  c(paste0("| ", paste(names(df), collapse = " | "), " |"),
    paste0("|", paste(rep("---", ncol(df)), collapse = "|"), "|"),
    apply(df, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |")))
}

summary_lines <- c(
  "# Effect of the KAP-68 fix on outgoing traffic",
  "",
  paste0("Generated by `analysis/fix_effect.R` on ", format(Sys.Date()), ". Aggregates only."),
  "",
  sprintf("Fix live at %s (restart of the web container, Apache serves only `public/`).", fmt_time(fix_time)),
  "",
  "## Periods",
  "",
  md_table(period_summary |> transmute(
    period,
    from = fmt_time(from), to = fmt_time(to),
    days = sprintf("%.1f", days),
    requests = format(requests, big.mark = ","),
    `requests/day` = format(round(requests_per_day), big.mark = ","),
    `MB out/day` = sprintf("%.1f", mb_out_per_day)
  )),
  "",
  "## Exposed files (probe answered with 2xx)",
  "",
  md_table(period_summary |> transmute(
    period,
    `exposure probes` = format(exposure_probes, big.mark = ","),
    `answered 2xx` = format(exposed_2xx, big.mark = ","),
    `2xx per day` = sprintf("%.1f", exposed_per_day),
    `GB sent as 2xx` = sprintf("%.3f", exposed_gb),
    `/.git/objects 2xx` = format(git_objects_2xx, big.mark = ","),
    `/.git/objects GB` = sprintf("%.3f", git_objects_gb)
  )),
  "",
  sprintf("- Outgoing bytes per day: %.1f MB before, %.2f MB after (%.1f%% drop).", b$mb_out_per_day, a$mb_out_per_day, 100 * drop_bytes),
  sprintf("- Exposure probes answered with 2xx per day: %.1f before, %.2f after (%.1f%% drop).", b$exposed_per_day, a$exposed_per_day, 100 * drop_exposed),
  sprintf("- Requests per day: %s before, %s after: scanners keep coming, but get nothing.",
          format(round(b$requests_per_day), big.mark = ","), format(round(a$requests_per_day), big.mark = ",")),
  "",
  "## Status of exposure probes",
  "",
  md_table(status_of_probes |> transmute(period, status = status_class, requests = format(n, big.mark = ","), share = sprintf("%.1f%%", 100 * share))),
  "",
  "## Caveats",
  "",
  "- The two periods differ in length and season; rates per day are compared.",
  "- Proxy-style probes (`GET http://...`) are not counted as exposure probes; the server answers them with its normal page.",
  "- No requests are logged between 10 Oct 23:53 and 11 Oct 00:11 UTC, around the weekly log rotation. It is not corrected for; it is 18 minutes out of 6.4 days."
)
writeLines(summary_lines, "analysis/fix_effect_summary.md")
cat(summary_lines, sep = "\n")

# Figure ----------------------------------------------------------------------
surface <- "#fcfcfb"
daily <- requests |>
  mutate(kind = if_else(exposed, "Exposed files served (2xx)", "Everything else")) |>
  group_by(period, day, kind) |>
  summarise(mb = sum(bytes, na.rm = TRUE) / 1e6, .groups = "drop")
p <- ggplot(daily, aes(day, mb, fill = kind)) +
  geom_col(width = 0.9) +
  facet_wrap(~period, scales = "free", labeller = as_labeller(c(
    before = "Before the fix", after = "After the fix"
  ))) +
  scale_fill_manual(values = c("Exposed files served (2xx)" = "#d03b3b", "Everything else" = "#2a78d6")) +
  scale_y_continuous(labels = scales::label_comma(), expand = expansion(c(0, 0.05))) +
  labs(
    title = "Closing the exposed .git folder removed almost all outgoing traffic",
    subtitle = "Outgoing response megabytes per day (note the different y-scales)",
    x = NULL, y = "MB per day",
    caption = sprintf("Source: kapsiar.sk access log, %s to %s. Fix live %s.", format(min(requests$time), "%d %b"), format(max(requests$time), "%d %b %Y"), fmt_time(fix_time))
  ) +
  theme_minimal(base_size = 11) +
  theme(
    plot.background = element_rect(fill = surface, colour = NA),
    panel.grid.minor = element_blank(), panel.grid.major.x = element_blank(),
    panel.grid.major.y = element_line(colour = "#e6e5e1", linewidth = 0.3),
    plot.title = element_text(face = "bold"), plot.caption = element_text(hjust = 0),
    legend.position = "top", legend.justification = "left", legend.title = element_blank()
  )
ggsave("analysis/figures/06_fix_effect.png", p, width = 9, height = 4.5, dpi = 200, bg = surface)
