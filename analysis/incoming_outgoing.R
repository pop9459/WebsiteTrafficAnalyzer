# Incoming vs outgoing HTTP traffic of kapsiar.sk (KAP-54, reframed).
#
# The 64.3 GB incoming / 5.2 GB outgoing of 09/2025 cannot be traced to a
# source, so this script explains today's in/out pattern with the %I / %O
# fields of the extended log format (available since 7 Oct 2026).
#
# Usage (from the repo root, after data-raw/import_logs.R):
#   Rscript analysis/incoming_outgoing.R
# Writes analysis/incoming_outgoing.md and analysis/figures/20_bytes_in_out_daily.png.
# Aggregates only: no addresses, no single requests.

suppressPackageStartupMessages({
  library(dplyr)
  library(ggplot2)
})
devtools::load_all(quiet = TRUE)
invisible(Sys.setlocale("LC_TIME", "C"))

requests <- readRDS("data/processed/requests.rds")
ext <- requests |>
  filter(!is.na(bytes_in)) |>
  mutate(date = as.Date(time, tz = "UTC"))
stopifnot(nrow(ext) > 0)

mb <- function(x) x / 1e6
fmt_mb <- function(x) formatC(mb(x), format = "f", digits = 1, big.mark = ",")
fmt_int <- function(x) formatC(x, format = "d", big.mark = ",")
fmt_pct <- function(x) sprintf("%.1f%%", 100 * x)
md_table <- function(df) {
  df[] <- lapply(df, as.character)
  c(
    paste0("| ", paste(names(df), collapse = " | "), " |"),
    paste0("|", paste(rep("---", ncol(df)), collapse = "|"), "|"),
    apply(df, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |"))
  )
}

# ---- totals ------------------------------------------------------------------
tot_in <- sum(ext$bytes_in)
tot_out <- sum(ext$bytes_out, na.rm = TRUE)
ratio <- tot_in / tot_out
provider_ratio <- 64.3 / 5.2
days <- n_distinct(ext$date)

by_class <- ext |>
  group_by(client_class) |>
  summarise(
    requests = n(), mb_in = sum(bytes_in), mb_out = sum(bytes_out, na.rm = TRUE),
    median_in = median(bytes_in), median_out = median(bytes_out, na.rm = TRUE),
    .groups = "drop"
  ) |>
  mutate(ratio = mb_in / mb_out, share_in = mb_in / tot_in, share_out = mb_out / tot_out) |>
  arrange(desc(requests))

# ---- daily -------------------------------------------------------------------
daily <- ext |>
  group_by(date) |>
  summarise(requests = n(), mb_in = mb(sum(bytes_in)), mb_out = mb(sum(bytes_out, na.rm = TRUE)), .groups = "drop") |>
  mutate(ratio = mb_in / mb_out)

long <- rbind(
  data.frame(date = daily$date, direction = "incoming (%I)", mb = daily$mb_in),
  data.frame(date = daily$date, direction = "outgoing (%O)", mb = daily$mb_out)
)
p <- long |>
  ggplot(aes(date, mb, colour = direction)) +
  geom_line(linewidth = 0.7) +
  scale_y_log10() +
  labs(
    title = "Daily HTTP bytes in and out, kapsiar.sk",
    subtitle = "Extended log format only (from 7 Oct 2026); log scale",
    x = NULL, y = "MB per day", colour = NULL
  ) +
  theme_minimal(base_size = 11) +
  theme(legend.position = "bottom")
dir.create("analysis/figures", showWarnings = FALSE)
ggsave("analysis/figures/20_bytes_in_out_daily.png", p, width = 8, height = 4, dpi = 150)

# ---- probe families by bytes in ------------------------------------------------
fam <- ext |>
  filter(probe_family != "none") |>
  group_by(probe_family) |>
  summarise(requests = n(), mb_in = mb(sum(bytes_in)), mb_out = mb(sum(bytes_out, na.rm = TRUE)),
            mean_in = mean(bytes_in), .groups = "drop") |>
  mutate(share_of_in = mb_in / mb(tot_in)) |>
  arrange(desc(mb_in)) |>
  slice_head(n = 8)

# ---- response time -------------------------------------------------------------
timing <- ext |>
  filter(!is.na(duration_us)) |>
  group_by(client_class) |>
  summarise(
    requests = n(),
    median_ms = median(duration_us) / 1000,
    p95_ms = quantile(duration_us, 0.95) / 1000,
    .groups = "drop"
  ) |>
  arrange(desc(requests))

# Largest single request, as a number only.
max_in <- max(ext$bytes_in)
p99_in <- quantile(ext$bytes_in, 0.99)

# ---- report --------------------------------------------------------------------
md <- c(
  "# Incoming vs outgoing HTTP traffic (KAP-54)",
  "",
  "Generated by `analysis/incoming_outgoing.R`. Aggregates only.",
  "",
  "## Question",
  "",
  "The provider reported 64.3 GB incoming and 5.2 GB outgoing for 09/2025, an in/out ratio of 12.4. Nobody knows the source of that figure, so this analysis asks what today's HTTP traffic looks like with the `%I` (bytes received, including headers) and `%O` (bytes sent, including headers) fields, and whether HTTP traffic can produce a pattern like that.",
  "",
  "## Data",
  "",
  sprintf("- Requests with `%%I`/`%%O` (extended format, %s to %s): %s of %s (%d days).",
          min(ext$date), max(ext$date), fmt_int(nrow(ext)), fmt_int(nrow(requests)), days),
  "- `%I` and `%O` count the whole request and response on the wire (headers included), before TLS and without Cloudflare's own overhead; they are not the provider's network counters.",
  "- Requests rejected before Apache logs a size have no value and are left out.",
  "",
  "## Totals",
  "",
  sprintf("- Incoming: **%s MB**; outgoing: **%s MB**.", fmt_mb(tot_in), fmt_mb(tot_out)),
  sprintf("- Ratio in/out: **%.3f** (the provider's 09/2025 ratio: %.1f).", ratio, provider_ratio),
  sprintf("- Per day: median %.1f MB in, %.1f MB out; the day ratio ranges from %.3f to %.3f.",
          median(daily$mb_in), median(daily$mb_out), min(daily$ratio), max(daily$ratio)),
  sprintf("- Per request: median %d bytes in, %d bytes out; 99th percentile of bytes in: %s; largest single request in: %s bytes.",
          as.integer(median(ext$bytes_in)), as.integer(median(ext$bytes_out, na.rm = TRUE)),
          fmt_int(round(p99_in)), fmt_int(max_in)),
  "",
  "![Daily bytes in and out](figures/20_bytes_in_out_daily.png)",
  "",
  "## By client class",
  "",
  md_table(by_class |> transmute(
    client_class, requests = fmt_int(requests),
    `MB in` = fmt_mb(mb_in), `MB out` = fmt_mb(mb_out),
    `ratio in/out` = sprintf("%.3f", ratio),
    `share of in` = fmt_pct(share_in), `share of out` = fmt_pct(share_out),
    `median bytes in` = as.integer(median_in), `median bytes out` = as.integer(median_out)
  )),
  "",
  "## Probe families by bytes in",
  "",
  "Top families of requests whose path is a probe (names are families, not paths).",
  "",
  md_table(fam |> transmute(
    probe_family, requests = fmt_int(requests),
    `MB in` = sprintf("%.2f", mb_in), `MB out` = sprintf("%.2f", mb_out),
    `mean bytes in` = as.integer(mean_in), `share of all in` = fmt_pct(share_of_in)
  )),
  "",
  "## Response time (`%D`, per request)",
  "",
  md_table(timing |> transmute(
    client_class, requests = fmt_int(requests),
    `median ms` = sprintf("%.2f", median_ms), `p95 ms` = sprintf("%.2f", p95_ms)
  )),
  "",
  "## Conclusion",
  "",
  sprintf("- Today's HTTP in/out ratio is %.2f, against %.1f for the provider's 09/2025 figure: about %.0f times lower. Incoming and outgoing bytes are almost equal, because most requests come from bots and scanners that get a short page or error back (about 500 bytes each way).",
          ratio, provider_ratio, provider_ratio / ratio),
  sprintf("- HTTP requests bring in %s MB over %d days, about %.1f MB per day. The provider's 64.3 GB in one month is about %s MB per day, %.0f times that.",
          fmt_mb(tot_in), days, mb(tot_in) / days, fmt_int(round(64.3e3 / 30)), 64.3e3 / 30 / (mb(tot_in) / days)),
  sprintf("- Only %s of %s requests send more than 10 KB in (the largest is %s bytes); the 99th percentile is %s bytes. The only classes with more bytes in than out are small (unknown: ratio %.1f, %s requests) and cannot matter at the scale of gigabytes.",
          fmt_int(sum(ext$bytes_in > 10000)), fmt_int(nrow(ext)), fmt_int(max_in), fmt_int(round(p99_in)),
          by_class$ratio[by_class$client_class == "unknown"], fmt_int(by_class$requests[by_class$client_class == "unknown"])),
  "- A ratio of 12 needs about 12 times more bytes received than sent. With HTTP to this site that would take sustained large request bodies (uploads), and the logs show almost none. Today's HTTP traffic cannot produce that pattern.",
  "- This supports the earlier finding in `analysis/history_other_services.md`: the 09/2025 spike was not HTTP traffic to kapsiar.sk. Another service on the VPS (or non-HTTP traffic) is the likely source. Proving it needs the provider's per-day graph or per-service counters.",
  "",
  "Limits: only 7 Oct to 21 Oct 2026 has `%I`/`%O`; September 2025 has no byte fields at all, so this is a comparison of patterns, not a measurement of that month. Scanners downloading `.git` objects stopped after the KAP-68 fix, so outgoing bytes are lower now than before."
)
writeLines(md, "analysis/incoming_outgoing.md")
cat("wrote analysis/incoming_outgoing.md\n")
